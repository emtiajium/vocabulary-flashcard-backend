import { DataSource } from 'typeorm';
// NOTE: `globalSetup`/`globalTeardown` are not processed by jest's `moduleNameMapper`,
// therefore only relative imports are allowed in the whole include-chain of this file.
import DatabaseConfig from '../../src/common/persistence/DatabaseConfig';

const MIGRATIONS_GLOB = 'migrations/*.ts';

/**
 * Builds a lightweight DataSource which is only meant to run the real migrations
 * against the (in-memory) PGlite database. Entities are intentionally omitted
 * because `migration:run` never needs entity metadata.
 *
 * It mirrors `src/common/persistence/TypeormConfig.ts` (the DataSource used by the
 * `migration:run` npm script), including the absence of a custom naming strategy:
 * some migrations rely on the constraint names generated by TypeORM's default one.
 */
function createMigrationDataSource(): DataSource {
    const { type, host, port, username, password, database } = new DatabaseConfig();

    return new DataSource({
        type,
        host,
        port,
        username,
        password,
        database,
        synchronize: false,
        logging: false,
        entities: [],
        migrations: [`${process.cwd()}/${MIGRATIONS_GLOB}`],
    });
}

export async function runMigrations(): Promise<void> {
    const dataSource = createMigrationDataSource();

    await dataSource.initialize();

    try {
        // `transaction: 'none'` is required: the migrations execute their SQL through
        // `queryRunner.connection.query(...)` (a different pooled connection).
        // PGlite multiplexes every connection over a single Postgres session and its
        // socket server only drains the queue of the connection which owns the open
        // transaction, so running the migrations inside a transaction dead-locks.
        await dataSource.runMigrations({ transaction: 'none' });
    } finally {
        await dataSource.destroy();
    }
}
